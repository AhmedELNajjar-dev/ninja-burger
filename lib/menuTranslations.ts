/**
 * Returns the localized description of a menu item.
 */
export function getLocalizedDescription(
  nameEn?: string | null,
  nameAr?: string | null,
  descriptionAr?: string | null,
  isArabic?: boolean,
  descriptionEn?: string | null
): string | null {
  if (isArabic) {
    return descriptionAr || null
  }
  if (descriptionEn && descriptionEn.trim().length > 0) {
    return descriptionEn
  }
  if (isArabic) {
    return descriptionAr || null
  }

  // Check exact lookup by English name
  if (nameEn && MENU_ITEM_DESCRIPTIONS_EN[nameEn]) {
    return MENU_ITEM_DESCRIPTIONS_EN[nameEn]
  }

  // Check exact lookup by Arabic name
  if (nameAr && MENU_ITEM_DESCRIPTIONS_EN[nameAr]) {
    return MENU_ITEM_DESCRIPTIONS_EN[nameAr]
  }

  // Dynamic fallback: translate Arabic ingredient tokens
  if (descriptionAr) {
    let translated = descriptionAr
    for (const [regex, replacement] of INGREDIENT_TERMS) {
      translated = translated.replace(regex, replacement)
    }
    return translated
  }

  return null
}
